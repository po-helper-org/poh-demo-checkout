/**
 * Модуль метрик посещений и успешных транзакций.
 * Экспортирует замыкание с счётчиками и функциями управления.
 *
 * **Ограничение хранение:** Счётчики хранятся в памяти процесса и сбрасываются при
 * перезапуске сервиса. Это осознанное архитектурное решение демо-сервиса: отсутствие
 * персистентности упрощает код и позволяет сосредоточиться на контуре производства,
 * а не на хранении данных. На графиках метрики будут обнуляться после каждого
 * перезапуска, что является свойством архитектуры, а не ошибкой.
 */
export const counters = (() => {
  let visits = 0;
  let successes = 0;

  return {
    /**
     * Инкремент счётчика посещений.
     * Вызывается при каждом POST /quote.
     * @returns {void}
     */
    incVisit: () => {
      visits += 1;
    },

    /**
     * Инкремент счётчика успешных транзакций.
     * Вызывается при каждом успешном quote() (HTTP 200).
     * @returns {void}
     */
    incSuccess: () => {
      successes += 1;
    },

    /**
     * Получение текущих значений счётчиков.
     * @returns {{visits: number, successes: number}}
     */
    getStats: () => ({
      visits,
      successes
    })
  };
})();
